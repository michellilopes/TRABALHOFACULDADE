# 4. FUNÇÃO PARA CONSULTAR A API

def buscar_indicador(codigo, nome):

    url = (
        f"https://api.worldbank.org/v2/"
        f"country/all/indicator/{codigo}"
        f"?format=json&per_page=20000"
    )

    resposta = requests.get(url)

    if resposta.status_code != 200:
        print("Erro ao acessar:", codigo)
        return pd.DataFrame()

    dados = resposta.json()

    registros = dados[1]

    lista = []

    for item in registros:

        if item["countryiso3code"] in paises:

            lista.append({
                "Pais": paises[item["countryiso3code"]],
                "Codigo": item["countryiso3code"],
                "Ano": int(item["date"]),
                nome: item["value"]
            })

    return pd.DataFrame(lista)

